export function getProceduralLessonSeed(
  rankId: RankId,
  sequenceNumber: number
): ProceduralSeed {
  const categories = TOPIC_CATEGORIES[rankId];
  const flatScenarios: Array<{ category: string; scenario: string }> = [];
  for (const cat of categories) {
    for (const s of cat.scenarios) {
      flatScenarios.push({ category: cat.category, scenario: s });
    }
  }

  const idx = Math.max(0, sequenceNumber - 1);
  const scenarioItem = flatScenarios[idx % flatScenarios.length];
  const twistIdx = Math.floor(idx / flatScenarios.length) % TWIST_VARIATIONS.length;
  const tutorId = TUTOR_ROTATION[idx % TUTOR_ROTATION.length];

  return {
    rankId,
    sequenceNumber,
    topicCategory: scenarioItem.category,
    scenarioTitle: scenarioItem.scenario,
    twist: TWIST_VARIATIONS[twistIdx],
    tutorId,
  };
}

export function getRankById(rankId: RankId): RankDefinition {
  return RANKS.find((r) => r.id === rankId) ?? RANKS[0];
}

export function getNextRank(rankId: RankId): RankDefinition | null {
  const idx = RANKS.findIndex((r) => r.id === rankId);
  if (idx === -1 || idx >= RANKS.length - 1) return null;
  return RANKS[idx + 1];
}
